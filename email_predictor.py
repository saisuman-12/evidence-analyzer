import os
import joblib


# ============================================================
# PROJECT PATHS
# ============================================================

BASE_DIR = os.path.abspath(
    os.path.join(
        os.path.dirname(__file__),
        ".."
    )
)

MODEL_PATH = os.path.join(
    BASE_DIR,
    "models",
    "email_model.pkl"
)

VECTORIZER_PATH = os.path.join(
    BASE_DIR,
    "models",
    "email_tfidf_vectorizer.pkl"
)


# ============================================================
# EMAIL PREDICTION
# ============================================================

def predict_email(email_text):

    # Check model exists
    if not os.path.exists(MODEL_PATH):
        raise FileNotFoundError(
            f"Email model not found: {MODEL_PATH}"
        )

    # Check vectorizer exists
    if not os.path.exists(VECTORIZER_PATH):
        raise FileNotFoundError(
            f"TF-IDF vectorizer not found: {VECTORIZER_PATH}"
        )

    # Load the SAME model and vectorizer
    # generated by train_email_model.py
    model = joblib.load(
        MODEL_PATH
    )

    vectorizer = joblib.load(
        VECTORIZER_PATH
    )

    # Convert email into TF-IDF features
    email_tfidf = vectorizer.transform(
        [email_text]
    )

    # Make prediction
    prediction = model.predict(
        email_tfidf
    )[0]

    return prediction


